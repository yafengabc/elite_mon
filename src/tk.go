package main

// Tk UI backend (Windows / Linux), providing the same startLogging / runUI as the
// Win32 gui.go / win32.go; build tags pick one:
//
//	Windows: compiled only with explicit -tags gui,tk (default stays Win32, pure SDK)
//	Linux:   compiled with -tags gui (no Win32 on Linux)
//
// Uses modernc.org/tk9.0 (pure-Go port of Tk 9.0, no CGO, no bundled DLL):
//   - Complex static layout (top bar / tabs / text + scrollbars) is still built by a Tcl
//     script via eval.Eval — proven under Tk 8.6, and the commands are fully Tk 9.0
//     compatible.
//   - Callback-needing parts (button clicks, window close, periodic refresh) use the
//     tk9.0 native API: Command(func()) for buttons, self-rescheduling
//     TclAfter(ms, func()) for refresh, WmProtocol(func()) for close. That drops CGO and
//     avoids registering custom Tcl commands.
//
// Threading: tk9.0 must be called from the goroutine that initialized it (it locks the OS
// thread internally). Every eval / TclAfter / WmProtocol / Command callback runs on the Tk
// event-loop thread, so calling Tk from the refresh is safe; the HTTP server runs on another
// goroutine and never touches Tk. Window close goes through the WmProtocol callback, which
// os.Exit()s the whole process (the monitoring backend goes with it).

