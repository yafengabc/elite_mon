// runningTests reports whether the running binary is a go test build.
// On Windows the test binary is named xxx.test.exe, so checking ".test" alone misses it.
func runningTests() bool {
	base := strings.ToLower(filepath.Base(os.Args[0]))
	return strings.HasSuffix(base, ".test") || strings.HasSuffix(base, ".test.exe")
}

// startLogging redirects the log: in-memory ring buffer only, shown on the status tab.
// A GUI has no console, so the log is visible in the window; no log file next to the exe.
func startLogging() {
	if runningTests() {
		return
	}
	log.SetOutput(guiLogRing)
}
